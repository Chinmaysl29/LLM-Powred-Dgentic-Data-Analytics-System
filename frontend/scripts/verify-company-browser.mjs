async function publishedJob(job) {
  const deadline = Date.now() + 60000;
  while (Date.now() < deadline) {
    const response = await page.waitForResponse(r => r.url().includes('/api/v1/dataplane/dashboard?') && r.status() === 200, { timeout: Math.min(10000, deadline - Date.now()) });
    const dashboard = await response.json();
    const state = dashboard.jobs.find(j => j.id === job.id);
    if (state && ['FAILED', 'CANCELLED'].includes(state.status)) throw new Error(`Synthetic job did not finish: ${state.status}`);
    const artifact = dashboard.records.find(record => record.job_id === job.id);
    if (artifact) return artifact.id;
  }
  throw new Error('The exact submitted job did not publish an artifact');
}
